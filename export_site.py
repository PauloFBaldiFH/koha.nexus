#!/usr/bin/env python3
"""Build the English homepage and one static homepage/manual shell per panel language.

Edit site/templates and the hand-written site/locales dictionaries, then run
python3 export_site.py. --check validates committed output without writing it.
It also writes sitemap.xml and robots.txt for the public https://koha.nexus/ URLs.
The panel export remains generated by export_docs_preview.py.
"""
from __future__ import annotations

import argparse
from collections import Counter
from html import escape
from html.parser import HTMLParser
import json
import posixpath
from pathlib import Path
import re

from export_docs_preview import panel_languages

ROOT = Path(__file__).resolve().parent
SITE_URL = 'https://koha.nexus/'
OG_IMAGE = SITE_URL + 'windows/KohaNexusLogo.png'
OG_LOCALE = {'en': 'en_US', 'pt': 'pt_BR'}
LICENSE_URL = 'https://www.gnu.org/licenses/gpl-3.0.html'
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}
PLACEHOLDER = re.compile(r'\$\{[^{}]+\}|\{(?:\d+|[A-Za-z_]\w*)(?:![rsa])?(?::[^{}]*)?\}|%(?:\([^)]+\))?[#0+\-]*\d*(?:\.\d+)?[sdif]')


def languages():
    """Translated pages live under languages/ using the existing dictionary codes."""
    return [{**lang, 'folder': '' if lang['dict'] == 'en' else posixpath.join('languages', lang['dict']),
             'html': {'pt': 'pt-BR', 'zh': 'zh-Hans'}.get(lang['dict'], lang['dict'])}
            for lang in panel_languages()]


def page_path(lang, kind):
    return posixpath.join(lang['folder'], 'preview' if kind == 'preview' else '', 'index.html')


def public_url(lang, kind):
    folder = posixpath.dirname(page_path(lang, kind))
    return SITE_URL + (folder + '/' if folder else '')


def seo_text(locale, kind):
    """Search title and description. The optional "seo" group of a locale wins;
    languages without it keep their existing homepage/manual texts."""
    seo = locale.get('seo', {})
    if kind == 'home':
        return (seo.get('home_title', locale['home']['page_title']),
                seo.get('home_description', locale['home']['page_description']))
    ui = locale['manual_ui']
    return (seo.get('manual_title', 'koha.nexus · ' + ui['title']),
            seo.get('manual_description', ui['subtitle']))


def head_tags(lang, kind, title, description):
    """Canonical, Open Graph and (homepage only) SoftwareApplication data."""
    url = public_url(lang, kind)
    tags = ['<link rel="canonical" href="{}">'.format(url),
            '<meta property="og:type" content="{}">'.format('website' if kind == 'home' else 'article'),
            '<meta property="og:site_name" content="koha.nexus">',
            '<meta property="og:title" content="{}">'.format(escape(title)),
            '<meta property="og:description" content="{}">'.format(escape(description)),
            '<meta property="og:url" content="{}">'.format(url),
            '<meta property="og:image" content="{}">'.format(OG_IMAGE)]
    if lang['dict'] in OG_LOCALE:
        tags.append('<meta property="og:locale" content="{}">'.format(OG_LOCALE[lang['dict']]))
    tags.append('<meta name="twitter:card" content="summary">')
    if kind == 'home':
        data = {
            '@context': 'https://schema.org',
            '@type': 'SoftwareApplication',
            'name': 'koha.nexus',
            'description': description,
            'url': url,
            'inLanguage': lang['html'],
            'applicationCategory': 'BusinessApplication',
            'applicationSubCategory': 'Integrated library system installer and control panel for Koha',
            'operatingSystem': 'Windows 10, Windows 11 (WSL 2), Debian, Ubuntu',
            'downloadUrl': url + '#windows',
            'license': LICENSE_URL,
            'isAccessibleForFree': True,
            'offers': {'@type': 'Offer', 'price': '0', 'priceCurrency': 'BRL'},
            'author': {'@type': 'Person', 'name': 'Paulo F. Baldi FH'},
            'codeRepository': 'https://github.com/PauloFBaldiFH/koha.nexus',
        }
        tags.append('<script type="application/ld+json">' +
                    json.dumps(data, ensure_ascii=False).replace('<', '\\u003c') + '</script>')
    return '\n'.join(tags)


def relative(target, current):
    return posixpath.relpath(target, posixpath.dirname(current) or '.')


def placeholder_counts(text):
    return Counter(PLACEHOLDER.findall(text))


def read_locales(root=ROOT):
    result = {lang['dict']: json.loads((root / 'site/locales' / (lang['dict'] + '.json')).read_text(encoding='utf-8'))
              for lang in languages()}
    english = result['en']
    for code, data in result.items():
        for group in ('home', 'manual_ui'):
            assert set(data[group]) == set(english[group]), (code, group, 'missing/unknown translation keys')
            for key, value in data[group].items():
                assert isinstance(value, str) and value.strip(), (code, key, 'empty translation')
                assert placeholder_counts(value) == placeholder_counts(english[group][key]), (code, key, 'placeholder mismatch')
    return result


class Renderer(HTMLParser):
    def __init__(self, lang, kind, text, all_languages):
        super().__init__(convert_charrefs=False)
        self.lang, self.kind, self.text, self.all_languages = lang, kind, text, all_languages
        self.current = page_path(lang, kind)
        self.out = []
        self.skip = 0

    def links(self):
        return ''.join('<a data-language="{code}" lang="{html}" hreflang="{html}" href="{href}"{active}>{name}</a>'.format(
            code=lang['dict'], html=lang['html'], href=relative(page_path(lang, self.kind), self.current),
            active=' aria-current="page"' if lang['dict'] == self.lang['dict'] else '', name=escape(lang['name']))
            for lang in self.all_languages)

    def handle_starttag(self, tag, attrs):
        if self.skip:
            if tag not in VOID:
                self.skip += 1
            return
        attrs = dict(attrs)
        if tag == 'html':
            attrs.update(lang=self.lang['html'], dir=self.lang['dir'])
        if tag == 'body':
            attrs['data-language'] = self.lang['dict']
        for marker, dest in [('data-i18n-ph', 'placeholder'), ('data-i18n-aria', 'aria-label'), ('data-ui-aria', 'aria-label'),
                             ('data-i18n-meta', 'content'), ('data-ui-meta', 'content'), ('data-ui-title', 'title')]:
            if marker in attrs:
                attrs[dest] = self.text[attrs[marker]]
        if 'data-home' in attrs:
            attrs['href'] = relative(page_path(self.lang, 'home'), self.current) + ('#' + attrs['data-home'] if attrs['data-home'] else '')
        elif tag in ('link', 'script', 'img', 'a'):
            for name in ('src', 'href'):
                value = attrs.get(name, '')
                if value.startswith(('site/', 'docs/', 'README.md', 'preview/assets/')):
                    attrs[name] = relative(value, self.current) + ('/' if value.endswith('/') else '')
        if tag == 'input' and attrs.get('id') == 'kp-search':
            attrs['placeholder'] = self.text['search']
        if attrs.get('id') == 'kp-app':
            attrs['data-static-language'] = self.lang['code']
            attrs['data-site-home'] = relative('index.html', self.current)
        start = '<' + tag + ''.join(' ' + k + ('' if v is None else '="' + escape(v, quote=True) + '"') for k, v in attrs.items()) + '>'
        self.out.append(start)
        if 'data-language-links' in attrs:
            self.out.append(self.links())
            self.skip = 1
        elif 'data-language-select' in attrs:
            self.out.append(''.join('<option value="{}"{}>{}</option>'.format(lang['code'], ' selected' if lang['dict'] == self.lang['dict'] else '', escape(lang['name'])) for lang in self.all_languages))
            self.skip = 1
        else:
            key = attrs.get('data-i18n') or attrs.get('data-ui')
            if key:
                value = self.text[key]
                self.out.append(value if self.kind == 'home' else escape(value))
                if tag not in VOID:
                    self.skip = 1

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        if self.skip:
            self.skip -= 1
            if self.skip:
                return
        self.out.append('</' + tag + '>')

    def handle_data(self, data):
        if not self.skip:
            self.out.append(data)

    def handle_entityref(self, name):
        self.handle_data('&' + name + ';')

    def handle_charref(self, name):
        self.handle_data('&#' + name + ';')

    def handle_comment(self, data):
        if not self.skip:
            self.out.append('<!--' + data + '-->')

    def handle_decl(self, decl):
        self.out.append('<!' + decl + '>')

    def handle_pi(self, data):
        self.out.append('<?' + data + '>')


def render_pages(source_root=ROOT):
    all_languages = languages()
    locales = read_locales(source_root)
    pages = {}
    for lang in all_languages:
        for kind in ('home', 'preview'):
            current = page_path(lang, kind)
            text = locales[lang['dict']]['home' if kind == 'home' else 'manual_ui']
            title, description = seo_text(locales[lang['dict']], kind)
            # seo_title is element text: the homepage inserts its texts as HTML.
            extra = {'seo_title': escape(title) if kind == 'home' else title, 'seo_description': description}
            if kind == 'preview':
                extra['download_link'] = locales[lang['dict']]['home']['win_d_t']
            template = (source_root / 'site/templates' / (kind + '.html')).read_text(encoding='utf-8')
            renderer = Renderer(lang, kind, {**text, **extra}, all_languages)
            renderer.feed(template)
            renderer.close()
            html = ''.join(renderer.out)
            alternates = '\n'.join('<link rel="alternate" hreflang="{}" href="{}">'.format(
                other['html'], public_url(other, kind)) for other in all_languages)
            alternates += '\n<link rel="alternate" hreflang="x-default" href="' + public_url(all_languages[0], kind) + '">'
            html = html.replace('</head>', head_tags(lang, kind, title, description) + '\n' + alternates + '\n</head>')
            messages = {k: text[k] for k in ('ct_sending', 'ct_ok', 'ct_err', 'network_empty', 'network_error')} if kind == 'home' else text
            html = html.replace('{{MESSAGES}}', json.dumps(messages, ensure_ascii=False).replace('<', '\\u003c'))
            html = html.replace('{{LANG}}', lang['code']).replace('{{HOME}}', relative('index.html', current))
            pages[current] = html
    return pages


def render_sitemap():
    """Every homepage and manual, each with its language alternates."""
    all_languages = languages()
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for kind in ('home', 'preview'):
        for lang in all_languages:
            out.append('  <url>')
            out.append('    <loc>{}</loc>'.format(public_url(lang, kind)))
            for other in all_languages:
                out.append('    <xhtml:link rel="alternate" hreflang="{}" href="{}"/>'.format(other['html'], public_url(other, kind)))
            out.append('    <xhtml:link rel="alternate" hreflang="x-default" href="{}"/>'.format(public_url(all_languages[0], kind)))
            out.append('    <priority>{}</priority>'.format('1.0' if kind == 'home' and lang['dict'] in ('en', 'pt') else '0.8'))
            out.append('  </url>')
    out.append('</urlset>')
    return '\n'.join(out) + '\n'


def render_robots():
    return 'User-agent: *\nAllow: /\n\nSitemap: ' + SITE_URL + 'sitemap.xml\n'


def render_files(source_root=ROOT):
    """Everything the generator owns: the HTML pages plus sitemap.xml and robots.txt."""
    return {**render_pages(source_root), 'sitemap.xml': render_sitemap(), 'robots.txt': render_robots()}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--out', type=Path, default=ROOT, help='Output directory (default: repository root)')
    args = parser.parse_args(argv)
    pages = render_files()
    stale = []
    for rel, text in pages.items():
        path = args.out / rel
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    if stale:
        print('Stale site pages: ' + ', '.join(stale))
        return 1
    print(f'{len(pages) - 2} pages across {len(languages())} languages ' + ('are up to date' if args.check else 'written'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
