"""The README's table of catalogues, generated from targets.json.

    python -m sru_gateway.status_table           # prints the table
    python -m sru_gateway.status_table --write   # rewrites it in README.md

The table sits between the two marker comments below; tests fail when it
no longer matches targets.json, so the file stays the one source of truth.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

from . import targets as tg
from .config import TARGETS_FILE

README = Path(__file__).resolve().parents[1] / "README.md"
BEGIN = "<!-- targets:begin (generated by python -m sru_gateway.status_table --write) -->"
END = "<!-- targets:end -->"
ORDER = {s: i for i, s in enumerate(tg.STATUSES)}


def _where(t: tg.Target) -> str:
    if t.kind == "zeus":
        return f"Zeus `targets[{t.target_index}]`"
    if t.kind == "pergamum":
        return "Rede Pergamum (CRP)"
    if t.kind == "z3950":
        return f"`{t.host}:{t.port}/{t.db}`"
    if t.kind == "sru":
        return f"`{t.url}`"
    return ""


def render(table: dict[str, tg.Target]) -> str:
    counts = Counter(t.status for t in table.values())
    lines = [", ".join(f"{counts[s]} {s}" for s in tg.STATUSES if counts[s]) + f" ({len(table)} in all).", "",
             "| id | Catalogue | Status | Kind | Address | Note |", "|---|---|---|---|---|---|"]
    for t in sorted(table.values(), key=lambda t: ORDER[t.status]):
        lines.append(f"| `{t.id}` | {t.name} | {t.status} | {t.kind} | {_where(t)} | {t.note.replace('|', '/')} |")
    return "\n".join(lines)


def block(table: dict[str, tg.Target]) -> str:
    return f"{BEGIN}\n{render(table)}\n{END}"


def readme_block(text: str) -> str | None:
    start, end = text.find(BEGIN), text.find(END)
    return text[start:end + len(END)] if 0 <= start < end else None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m sru_gateway.status_table")
    ap.add_argument("--write", action="store_true", help="rewrite the table in README.md")
    args = ap.parse_args(argv)
    new = block(tg.load(TARGETS_FILE))
    if not args.write:
        print(new)
        return 0
    text = README.read_text(encoding="utf-8")
    old = readme_block(text)
    if old is None:
        print(f"{README}: the marker comments are missing", file=sys.stderr)
        return 1
    README.write_text(text.replace(old, new), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
